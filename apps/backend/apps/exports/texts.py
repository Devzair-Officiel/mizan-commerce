def status_label(shop: Shop, status: str, lang: str) -> str:
    """Libellé du statut selon le catalogue et le mode de remise, comme la page."""
    texts = TEXTS[lang]
    kind = shop.catalog_kind or 'both'
    if status == 'to_prepare':
        return texts[f'status.to_prepare.{kind}']
    if status == 'shipped':
        if kind == 'services':
            return texts['status.shipped.services']
        mode = shop.fulfillment_mode
        return texts[f'status.shipped.{mode if mode in ("on_site", "delivery") else "other"}']  # noqa: E501
    return texts[f'status.{status}']
